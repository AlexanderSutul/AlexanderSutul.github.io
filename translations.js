const supportedLanguages = Object.keys(translations);

const getBrowserLanguage = () => {
  const browserLanguages =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language];

  return (
    browserLanguages
      .map((language) => language.toLowerCase().split("-")[0])
      .find((language) => supportedLanguages.includes(language)) || "en"
  );
};

const getInitialLanguage = () => {
  const params = new URLSearchParams(window.location.search);
  const requestedLanguage = params.get("lang");
  const savedLanguage = localStorage.getItem("language");

  if (requestedLanguage === "en" || requestedLanguage === "de") {
    return requestedLanguage;
  }

  if (window.location.pathname.includes("/de/")) {
    return "de";
  }

  if (savedLanguage === "en" || savedLanguage === "de") {
    return savedLanguage;
  }

  return getBrowserLanguage();
};

const setUrlLanguage = (language) => {
  const url = new URL(window.location.href);
  url.searchParams.set("lang", language);
  window.history.replaceState({}, "", url);
};

const applyLanguage = (language, updateUrl = false) => {
  const dictionary = translations[language] || translations.en;

  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];

    if (translation) {
      element.textContent = translation;
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nAriaLabel];

    if (translation) {
      element.setAttribute("aria-label", translation);
    }
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === language;

    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("language", language);

  if (updateUrl) {
    setUrlLanguage(language);
  }
};

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.language, true);
  });
});

applyLanguage(getInitialLanguage());
